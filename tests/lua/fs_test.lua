local fs = winter.fs
local n, fail = 0, 0
local function ok(c, m) n = n + 1; if not c then fail = fail + 1; print("FAIL: " .. m) end end
local function eq(a, b, m) ok(a == b, m .. " (got " .. tostring(a) .. ", want " .. tostring(b) .. ")") end
local base = os.getenv("WT") .. "/work"
os.execute("rm -rf " .. base)
ok(fs.mkdir(base .. "/a/b/c", {parents = true}), "mkdir -p")
ok(fs.mkdir(base .. "/a"), "mkdir existing dir is success")
local r, err = fs.mkdir(base .. "/x/y")  -- no parents
ok(r == nil and err, "mkdir without parents fails: " .. tostring(err))
ok(fs.write(base .. "/a/f.txt", "hello"), "write")
ok(fs.write(base .. "/a/f.txt", " world", {append = true}), "append")
eq(fs.read(base .. "/a/f.txt"), "hello world", "read")
local d, e = fs.read(base .. "/nope")
ok(d == nil and e:find("nope"), "read missing -> nil, err")
ok(fs.write(base .. "/p/q/r.txt", "x", {parents = true}), "write parents")
ok(fs.is_file(base .. "/p/q/r.txt") and fs.is_dir(base .. "/p/q"), "is_file/is_dir")
ok(not fs.exists(base .. "/zzz"), "exists false")
local st = fs.stat(base .. "/a/f.txt")
eq(st.type, "file", "stat type"); eq(st.size, 11, "stat size"); ok(st.mtime > 1e9, "stat mtime")
eq(fs.stat(base .. "/a").type, "directory", "stat dir")
ok(fs.stat(base .. "/none") == nil, "stat missing nil")
fs.write(base .. "/a/run.sh", "#!/bin/sh\n"); os.execute("chmod +x " .. base .. "/a/run.sh")
ok(fs.executable(base .. "/a/run.sh") and not fs.executable(base .. "/a/f.txt"), "executable")
os.execute("ln -s f.txt " .. base .. "/a/lnk")
eq(fs.stat(base .. "/a/lnk").type, "link", "stat does not follow links")
local ents = fs.readdir(base .. "/a")
local names = {}
for _, e2 in ipairs(ents) do names[#names + 1] = e2.name .. ":" .. e2.type end
eq(table.concat(names, ","), "b:directory,f.txt:file,lnk:link,run.sh:file", "readdir sorted w/ types")
ok(fs.readdir(base .. "/none") == nil, "readdir missing nil")
ok(fs.rename(base .. "/a/f.txt", base .. "/a/g.txt") and fs.exists(base .. "/a/g.txt"), "rename")
ok(fs.remove(base .. "/a/g.txt") and not fs.exists(base .. "/a/g.txt"), "remove")
ok(fs.remove(base .. "/p", {recursive = true}) and not fs.exists(base .. "/p"), "remove -r")
eq(fs.realpath(base .. "/a/b/../b/c"), base .. "/a/b/c", "realpath")
ok(fs.realpath(base .. "/missing") == nil, "realpath missing nil")
-- pure path functions
eq(fs.joinpath("a", "b/", "/c", "", "d"), "a/b/c/d", "joinpath")
eq(fs.joinpath("/", "x"), "/x", "joinpath root")
eq(fs.dirname("/a/b/c.txt"), "/a/b", "dirname"); eq(fs.dirname("c.txt"), ".", "dirname bare")
eq(fs.dirname("/c"), "/", "dirname root child"); eq(fs.dirname("/a/b/"), "/a", "dirname trailing slash")
eq(fs.basename("/a/b/c.txt"), "c.txt", "basename"); eq(fs.basename("/a/b/"), "b", "basename trailing"); eq(fs.basename("/"), "/", "basename root")
eq(fs.normalize("/a/./b/../c//d/"), "/a/c/d", "normalize")
eq(fs.normalize("~/x"), os.getenv("HOME") .. "/x", "normalize ~")
-- stdpath
eq(fs.stdpath("config"), os.getenv("WT") .. "/cfg", "stdpath config")
ok(fs.stdpath("data"):match("/winter$"), "stdpath data")
ok(not pcall(fs.stdpath, "bogus"), "stdpath rejects unknown kind")
-- find / root
fs.write(base .. "/a/b/Cargo.toml", ""); fs.write(base .. "/a/b/c/main.rs", ""); fs.write(base .. "/a/b/c/lib.rs", "")
fs.mkdir(base .. "/a/.git"); fs.write(base .. "/a/.git/hidden.rs", "")
eq(fs.root({".git"}, base .. "/a/b/c/main.rs"), base .. "/a", "root from file finds .git")
eq(fs.root({"Cargo.toml", ".git"}, base .. "/a/b/c"), base .. "/a/b", "root nearest marker wins")
ok(fs.root({"no-such-marker-xyz"}, base .. "/a/b/c") == nil, "root none -> nil")
eq(fs.root({"Cargo.*"}, base .. "/a/b/c"), base .. "/a/b", "root with glob marker")
local f = fs.find("*.rs", {path = base, limit = math.huge})
table.sort(f)
eq(#f, 2, "find glob downward skips .git"); eq(f[1], base .. "/a/b/c/lib.rs", "find result")
eq(#fs.find("Cargo.toml", {path = base}), 1, "find default limit 1")
eq(#fs.find({"main.rs", "lib.rs"}, {path = base, limit = 5}), 2, "find list of names")
eq(#fs.find("c", {path = base, type = "directory"}), 1, "find type=directory")
eq(#fs.find("c", {path = base, type = "file"}), 0, "find type=file excludes dirs")
local up = fs.find({"Cargo.toml"}, {path = base .. "/a/b/c", upward = true})
eq(up[1], base .. "/a/b/Cargo.toml", "find upward")
eq(#fs.find({".git"}, {path = base .. "/a/b/c", upward = true, stop = base .. "/a/b"}), 0, "upward honours stop")
ok(not pcall(fs.find, {}), "find rejects empty list")
print(("%d checks, %d failed"):format(n, fail))
os.exit(fail == 0 and 0 or 1)
